DROP TABLE IF EXISTS public.categorias;
DROP TABLE IF EXISTS public.perfiles;

DROP TYPE IF EXISTS tipo_rol;
DROP TYPE IF EXISTS estado_prenda;
DROP TYPE IF EXISTS estado_alquiler;
DROP TYPE IF EXISTS estado_whatsapp;

-- =========================================================================
-- 1. CREACIÓN DE TIPOS PERSONALIZADOS (ENUMS)
-- =========================================================================
CREATE TYPE tipo_rol AS ENUM ('admin', 'vendedor');
CREATE TYPE estado_prenda AS ENUM ('disponible', 'alquilado', 'en_lavanderia', 'mantenimiento');
CREATE TYPE estado_alquiler AS ENUM ('reservado', 'en_uso', 'devuelto', 'atrasado');
CREATE TYPE estado_whatsapp AS ENUM ('pendiente', 'enviado', 'fallido');

-- =========================================================================
-- 2. TABLA: PERFILES (Sincronizada con auth.users de Supabase)
-- =========================================================================
CREATE TABLE public.perfiles (
    id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
    nombre_completo TEXT NOT NULL,
    rol tipo_rol DEFAULT 'vendedor' NOT NULL,
    fecha_creacion TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- =========================================================================
-- 3. TABLA: CATEGORIAS
-- =========================================================================
CREATE TABLE public.categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE,
    fecha_creacion TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- =========================================================================
-- 4. TABLA: PRODUCTOS_CATALOGO (Modelos comerciales / Vista web)
-- =========================================================================
CREATE TABLE public.productos_catalogo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT REFERENCES public.categorias(id) ON DELETE SET NULL,
    nombre TEXT NOT NULL,
    descripcion TEXT,
    precio_alquiler NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    precio_garantia NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    imagen_url TEXT,
    fecha_creacion TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- =========================================================================
-- 5. TABLA: INVENTARIO_FISICO (Prendas reales con Talla/Color/Código único)
-- =========================================================================
CREATE TABLE public.inventario_fisico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_catalogo_id BIGINT REFERENCES public.productos_catalogo(id) ON DELETE CASCADE NOT NULL,
    codigo_barras TEXT UNIQUE NOT NULL, -- Código único o QR impreso en la etiqueta
    talla TEXT NOT NULL,
    color TEXT NOT NULL,
    estado estado_prenda DEFAULT 'disponible' NOT NULL,
    notas TEXT,
    ultima_actualizacion TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- =========================================================================
-- 6. TABLA: CLIENTES
-- =========================================================================
CREATE TABLE public.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_identidad TEXT UNIQUE NOT NULL, -- DNI, Cédula, RUC, etc.
    nombre_completo TEXT NOT NULL,
    telefono_whatsapp TEXT NOT NULL, -- Guardar siempre con formato internacional (ej: 51999888777)
    email TEXT,
    direccion TEXT,
    fecha_registro TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- =========================================================================
-- 7. TABLA: ALQUILERES (Cabecera del contrato de alquiler)
-- =========================================================================
CREATE TABLE public.alquileres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT REFERENCES public.clientes(id) ON DELETE RESTRICT NOT NULL,
    -- OPTIMIZACIÓN: Hacemos vendedor_id NULLABLE. Cuando un cliente reserva en línea
    -- en la landing page, aún no hay un vendedor asignado. Se asigna luego en el admin.
    vendedor_id UUID REFERENCES public.perfiles(id) ON DELETE RESTRICT,
    fecha_reserva TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    fecha_salida TIMESTAMP WITH TIME ZONE, -- Cuándo se retira físicamente la prenda
    fecha_devolucion_prevista TIMESTAMP WITH TIME ZONE NOT NULL, -- Fecha límite de entrega
    fecha_devolucion_real TIMESTAMP WITH TIME ZONE, -- Cuándo retornó realmente
    total_pago NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    garantia_dejada NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    estado estado_alquiler DEFAULT 'reservado' NOT NULL,
    observaciones TEXT
);

-- =========================================================================
-- 8. TABLA: DETALLES_ALQUILER (Prendas incluidas en cada transacción)
-- =========================================================================
CREATE TABLE public.detalles_alquiler (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alquiler_id BIGINT REFERENCES public.alquileres(id) ON DELETE CASCADE NOT NULL,
    inventario_fisico_id BIGINT REFERENCES public.inventario_fisico(id) ON DELETE RESTRICT NOT NULL,
    precio_applied NUMERIC(10, 2) NOT NULL -- Precio final acordado
);

-- =========================================================================
-- 9. TABLA: HISTORIAL_WHATSAPP (Auditoría de mensajes)
-- =========================================================================
CREATE TABLE public.historial_whatsapp (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alquiler_id BIGINT REFERENCES public.alquileres(id) ON DELETE SET NULL,
    cliente_id BIGINT REFERENCES public.clientes(id) ON DELETE CASCADE NOT NULL,
    tipo_mensaje TEXT NOT NULL, -- Ej: 'confirmacion_reserva', 'recordatorio_devolucion'
    estado estado_whatsapp DEFAULT 'pendiente' NOT NULL,
    waba_message_id TEXT, -- ID único que retorna la API de Meta (WhatsApp Business)
    fecha_envio TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- =========================================================================
-- 10. AUTOMATIZACIÓN: TRIGGER PARA SINCRONIZAR USUARIOS CON AUTH DE SUPABASE
-- =========================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.perfiles (id, nombre_completo, rol)
  VALUES (
    new.id, 
    COALESCE(new.raw_user_meta_data->>'nombre_completo', 'Nuevo Colaborador'), 
    COALESCE((new.raw_user_meta_data->>'rol')::tipo_rol, 'vendedor')
  );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

