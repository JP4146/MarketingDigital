-- Limpiar tablas si existen (para poder ejecutar el script desde cero si es necesario)
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
DROP FUNCTION IF EXISTS public.handle_new_user();
DROP TABLE IF EXISTS public.historial_whatsapp;
DROP TABLE IF EXISTS public.detalles_alquiler;
DROP TABLE IF EXISTS public.alquileres;
DROP TABLE IF EXISTS public.clientes;
