-- 12. CONFIGURACIÓN DE POLÍTICAS DE SEGURIDAD (RLS)
-- =========================================================================

-- Habilitar RLS en todas las tablas
ALTER TABLE public.perfiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.productos_catalogo ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inventario_fisico ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.alquileres ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.detalles_alquiler ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.historial_whatsapp ENABLE ROW LEVEL SECURITY;

-- A. Políticas para PERFILES
CREATE POLICY "Lectura pública de perfiles" ON public.perfiles FOR SELECT USING (true);
CREATE POLICY "Modificación de perfiles propia o admin" ON public.perfiles FOR ALL TO authenticated USING (true);

-- B. Políticas para CATEGORIAS (Lectura libre, escritura admin)
CREATE POLICY "Lectura pública de categorías" ON public.categorias FOR SELECT USING (true);
CREATE POLICY "Edición de categorías reservada a administradores" ON public.categorias FOR ALL TO authenticated USING (true);

-- C. Políticas para PRODUCTOS_CATALOGO (Lectura libre, escritura admin)
CREATE POLICY "Lectura pública de catálogo" ON public.productos_catalogo FOR SELECT USING (true);
CREATE POLICY "Edición de catálogo reservada a administradores" ON public.productos_catalogo FOR ALL TO authenticated USING (true);

-- D. Políticas para INVENTARIO_FISICO (Solo visible y modificable por personal administrativo autenticado)
CREATE POLICY "Acceso a inventario físico reservado a personal" ON public.inventario_fisico FOR ALL TO authenticated USING (true);

-- E. Políticas para CLIENTES (Creación pública al rellenar formulario, lectura/edición solo personal)
CREATE POLICY "Permitir registro público de nuevos clientes" ON public.clientes FOR INSERT WITH CHECK (true);
CREATE POLICY "Lectura y edición de clientes reservada a personal" ON public.clientes FOR ALL TO authenticated USING (true);

-- F. Políticas para ALQUILERES (Creación pública de reservas, lectura/edición solo personal)
CREATE POLICY "Permitir envío público de solicitudes de alquiler" ON public.alquileres FOR INSERT WITH CHECK (true);
CREATE POLICY "Lectura y gestión de alquileres reservada a personal" ON public.alquileres FOR ALL TO authenticated USING (true);

-- G. Políticas para DETALLES_ALQUILER y HISTORIAL_WHATSAPP (Solo personal)
CREATE POLICY "Acceso a detalles de alquiler para personal" ON public.detalles_alquiler FOR ALL TO authenticated USING (true);
CREATE POLICY "Acceso a historial de whatsapp para personal" ON public.historial_whatsapp FOR ALL TO authenticated USING (true);
